// build-offline-fonts.mjs
// Downloads the woff2 files for the fonts the active theme (monochrome-print)
// actually uses, and emits a self-contained src/styles/fonts.offline.css that
// references them with local relative url()s. Vite + vite-plugin-singlefile
// then inline these woff2 as base64 into the single offline HTML — so the deck
// renders with correct typography with NO network access.
//
// Run from the presentation/ dir:  node scripts/build-offline-fonts.mjs
import { mkdir, writeFile, rm } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT_DIR = resolve(__dirname, "../src/styles/fonts");
const OUT_CSS = resolve(__dirname, "../src/styles/fonts.offline.css");

// A modern desktop Chrome UA so Google Fonts serves woff2 (not legacy ttf).
const UA =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 " +
  "(KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36";

// Only the families the monochrome-print theme references (tokens.css):
//   --font-display-cn: "Noto Serif SC"   (Chinese — subset to glyphs used)
//   --font-display-en/body: "Source Serif 4"
//   --font-mono: "JetBrains Mono"
// The Chinese deck text is tiny, so we subset Noto Serif SC via &text=.
const CJK_TEXT = "（）切式手换播放數模術";
const FAMILIES = [
  {
    key: "source-serif-4",
    url: "https://fonts.googleapis.com/css2?family=Source+Serif+4:ital,wght@0,400;0,500;0,700;1,400;1,500&display=swap",
  },
  {
    key: "jetbrains-mono",
    url: "https://fonts.googleapis.com/css2?family=JetBrains+Mono:ital,wght@0,400;0,500;0,600;1,400&display=swap",
  },
  {
    key: "noto-serif-sc",
    url:
      "https://fonts.googleapis.com/css2?family=Noto+Serif+SC:wght@400;500;700;900&display=swap&text=" +
      encodeURIComponent(CJK_TEXT),
  },
];

async function fetchText(url) {
  const res = await fetch(url, { headers: { "User-Agent": UA } });
  if (!res.ok) throw new Error(`GET ${url} → ${res.status}`);
  return res.text();
}

async function fetchBuffer(url) {
  const res = await fetch(url, { headers: { "User-Agent": UA } });
  if (!res.ok) throw new Error(`GET ${url} → ${res.status}`);
  return Buffer.from(await res.arrayBuffer());
}

// For the Latin (English/mono) families we only need these subsets; the
// CDN also ships cyrillic/greek/vietnamese we never render. The CJK family
// is already a tiny &text= subset, so every face of it is kept.
const KEEP_SUBSETS = new Set(["latin", "latin-ext"]);

async function main() {
  await rm(OUT_DIR, { recursive: true, force: true });
  await mkdir(OUT_DIR, { recursive: true });

  const urlToFile = new Map(); // dedupe identical remote woff2 across faces
  const cssBlocks = [];
  for (const fam of FAMILIES) {
    const css = await fetchText(fam.url);
    const isCjk = fam.key === "noto-serif-sc";
    // Each face is optionally preceded by a `/* subset */` label comment.
    const re = /(?:\/\*\s*([\w-]+)\s*\*\/\s*)?(@font-face\s*\{[^}]*\})/g;
    let i = 0;
    let kept = 0;
    for (const match of css.matchAll(re)) {
      const subset = match[1];
      const block = match[2];
      if (!isCjk && subset && !KEEP_SUBSETS.has(subset)) continue;
      const m = block.match(/url\((https:[^)]+)\)\s*format\(['"]woff2['"]\)/);
      if (!m) continue; // only woff2 (modern UA guarantees this)
      const remoteUrl = m[1];
      let file = urlToFile.get(remoteUrl);
      if (!file) {
        file = `${fam.key}-${i++}.woff2`;
        const buf = await fetchBuffer(remoteUrl);
        await writeFile(resolve(OUT_DIR, file), buf);
        urlToFile.set(remoteUrl, file);
        console.log(`  ${file}  (${(buf.length / 1024).toFixed(1)} KB)`);
      }
      const local = block.replace(m[0], `url("./fonts/${file}") format("woff2")`);
      cssBlocks.push(local.trim());
      kept++;
    }
    console.log(`✓ ${fam.key}: ${kept} face(s), ${i} file(s)`);
  }

  const header =
    "/* fonts.offline.css — AUTO-GENERATED by scripts/build-offline-fonts.mjs.\n" +
    " * Self-hosted woff2 for the monochrome-print theme (Source Serif 4,\n" +
    " * JetBrains Mono, Noto Serif SC subset). No network / Google Fonts CDN.\n" +
    " * Regenerate after changing the active theme or the CJK glyphs used. */\n\n";
  await writeFile(OUT_CSS, header + cssBlocks.join("\n\n") + "\n");
  console.log(`\n✓ wrote ${OUT_CSS} (${cssBlocks.length} @font-face)`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
